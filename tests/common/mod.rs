//! Shared tooling for the integration tests.
//!
//! - `edgetx_src` / `Encoder`: EdgeTX's own report encoder compiled into a small harness
//!   (falls back to the Rust mirror when the source or a C++ compiler is missing).
//! - `Radio` / `Wiring`: a model of the physical radio. Tests set stick and switch
//!   positions; the wiring (the model's mixes) turns them into channel values.
//! - `Overlay`: the real binary, started with `--replay -` so the test feeds it report
//!   bytes on stdin like a virtual USB device.
//! - `Ws`: WebSocket client that reads the overlay's published state.

#![allow(dead_code)]


// WebSocket client

pub mod ws {
    use std::time::Duration;

    use futures_util::{SinkExt, StreamExt};
    use serde_json::Value;
    use tokio_tungstenite::tungstenite::Message;

    pub struct Ws {
        stream: tokio_tungstenite::WebSocketStream<
            tokio_tungstenite::MaybeTlsStream<tokio::net::TcpStream>,
        >,
        pub last: Value,
    }

    impl Ws {
        pub async fn connect(port: u16) -> Self {
            let (stream, _) = tokio_tungstenite::connect_async(format!("ws://127.0.0.1:{port}/ws"))
                .await
                .unwrap();
            let mut ws = Ws {
                stream,
                last: Value::Null,
            };
            ws.next().await;
            ws
        }

        async fn next(&mut self) -> &Value {
            loop {
                match self.stream.next().await {
                    Some(Ok(Message::Text(t))) => {
                        self.last = serde_json::from_str(&t).unwrap();
                        return &self.last;
                    }
                    Some(Ok(_)) => {}
                    other => panic!("websocket ended: {other:?}"),
                }
            }
        }

        /// Waits for a published state that satisfies `pred`.
        pub async fn wait_for(&mut self, what: &str, pred: impl Fn(&Value) -> bool) -> Value {
            if pred(&self.last) {
                return self.last.clone();
            }
            let deadline = tokio::time::Instant::now() + Duration::from_secs(8);
            loop {
                match tokio::time::timeout_at(deadline, self.next()).await {
                    Ok(v) if pred(v) => return v.clone(),
                    Ok(_) => {}
                    Err(_) => panic!("timed out waiting for {what}; last state:\n{:#}", self.last),
                }
            }
        }

        /// Waits for the next message, whatever it says.
        pub async fn recv(&mut self) -> Value {
            self.next().await.clone()
        }

        pub async fn command(&mut self, cmd: &str) {
            self.send_json(serde_json::json!({ "cmd": cmd })).await;
        }

        pub async fn send_json(&mut self, msg: Value) {
            self.stream
                .send(Message::Text(msg.to_string().into()))
                .await
                .unwrap();
        }
    }
}


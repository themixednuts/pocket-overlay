// the overlay process

pub struct Overlay {
    child: Child,
    stdin: ChildStdin,
    pub port: u16,
    pub dir: tempfile::TempDir,
    pub log: Arc<Mutex<Vec<String>>>,
    encoder: Encoder,
    pub wiring: Wiring,
    /// Hex of the last report sent, for recording evidence.
    pub last_report: String,
}

impl Overlay {
    pub fn start() -> Self {
        Self::start_with(None)
    }

    /// Starts the binary reading reports from stdin. `config` is written as overlay.toml
    /// first; otherwise the binary writes its defaults.
    pub fn start_with(config: Option<&str>) -> Self {
        Self::launch(&["--replay", "-"], config)
    }

    /// Starts the binary with other input arguments (`--demo`, `--replay <file>`).
    pub fn launch(input: &[&str], config: Option<&str>) -> Self {
        let dir = tempfile::tempdir().unwrap();
        let cfg = dir.path().join("overlay.toml");
        if let Some(text) = config {
            std::fs::write(&cfg, text).unwrap();
        }
        let mut child = Command::new(env!("CARGO_BIN_EXE_pocket-overlay"))
            .args(input)
            .args(["--port", "0", "--config"])
            .arg(&cfg)
            .current_dir(dir.path()) // no web/ override: test the embedded page
            .stdin(Stdio::piped())
            .stderr(Stdio::piped())
            .stdout(Stdio::null())
            .spawn()
            .unwrap();
        let stdin = child.stdin.take().unwrap();
        let log = Arc::new(Mutex::new(Vec::new()));
        let (port_tx, port_rx) = mpsc::channel();
        let stderr = child.stderr.take().unwrap();
        let log2 = log.clone();
        std::thread::spawn(move || {
            for line in BufReader::new(stderr).lines().map_while(Result::ok) {
                // first URL the app prints is the overlay's
                if let Some(rest) = line.split("http://127.0.0.1:").nth(1)
                    && let Ok(port) = rest.split('/').next().unwrap().parse::<u16>()
                {
                    let _ = port_tx.send(port);
                }
                log2.lock().unwrap().push(line);
            }
        });
        let port = port_rx
            .recv_timeout(Duration::from_secs(10))
            .unwrap_or_else(|_| panic!("overlay didn't start: {:?}", log.lock().unwrap()));
        Overlay {
            child,
            stdin,
            port,
            dir,
            log,
            encoder: Encoder::best(),
            wiring: Wiring::default_pocket(),
            last_report: String::new(),
        }
    }

    pub fn encoder_name(&self) -> &'static str {
        self.encoder.name()
    }

    pub fn line(&mut self, s: &str) {
        writeln!(self.stdin, "{s}").unwrap();
        self.stdin.flush().unwrap();
    }

    /// Sends channels straight through the Rust encoder (fast, for floods).
    pub fn channels_fast(&mut self, ch: &[i16; edgetx::CHANNELS]) {
        self.line(&to_hex(&edgetx::encode_classic(ch)));
    }

    pub fn channels(&mut self, ch: &[i16; edgetx::CHANNELS]) {
        let bytes = self.encoder.encode(ch);
        self.last_report = to_hex(&bytes);
        let line = self.last_report.clone();
        self.line(&line);
    }

    /// Puts the physical radio in `radio`'s position (through the current wiring).
    pub fn radio(&mut self, radio: &Radio) {
        let ch = self.wiring.channels(radio);
        self.channels(&ch);
    }

    pub fn url(&self, query: &str) -> String {
        format!("http://127.0.0.1:{}/{query}", self.port)
    }

    pub fn config_text(&self) -> String {
        std::fs::read_to_string(self.dir.path().join("overlay.toml")).unwrap()
    }
}

impl Drop for Overlay {
    fn drop(&mut self) {
        let _ = self.child.kill();
    }
}

/// Channel values joined with commas, as the page's `data-channels` shows them.
pub fn channel_key(ch: &[i16]) -> String {
    ch.iter().map(i16::to_string).collect::<Vec<_>>().join(",")
}

/// What the decoded channels should be: axes clamp to +-1024, buttons read +-1024.
pub fn expected_channels(ch: &[i16; edgetx::CHANNELS]) -> [i16; edgetx::CHANNELS] {
    let mut out = [0i16; edgetx::CHANNELS];
    for (i, v) in ch.iter().enumerate() {
        out[i] = if i < edgetx::AXES {
            (*v).clamp(-1024, 1024)
        } else if *v > 0 {
            1024
        } else {
            -1024
        };
    }
    out
}


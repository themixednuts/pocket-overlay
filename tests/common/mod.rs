/// Where every physical control is. Sticks and S1 are -1..=1 (up/right = +);
/// switch positions count from "away from the pilot" (0).
#[derive(Debug, Clone, Copy, Default, PartialEq)]
pub struct Radio {
    pub left_x: f32,
    pub left_y: f32,
    pub right_x: f32,
    pub right_y: f32,
    pub sa: u8,
    pub sb: u8,
    pub sc: u8,
    pub sd: u8,
    pub se: bool,
    pub s1: f32,
}

impl Radio {
    /// What EdgeTX's mixer outputs for a control at full weight: -100/+100 for 2-pos,
    /// -100/0/+100 for 3-pos, value*100 for analog.
    pub fn mixer_value(&self, target: Target) -> f32 {
        let two = |p: u8| if p == 0 { -1.0 } else { 1.0 };
        match target {
            Target::LeftX => self.left_x,
            Target::LeftY => self.left_y,
            Target::RightX => self.right_x,
            Target::RightY => self.right_y,
            Target::SA => two(self.sa),
            Target::SD => two(self.sd),
            Target::SB => self.sb as f32 - 1.0,
            Target::SC => self.sc as f32 - 1.0,
            Target::SE => two(self.se as u8),
            Target::S1 => self.s1,
        }
    }
}

/// The model's mixes: which channel each control drives, and whether it's reversed.
#[derive(Debug, Clone, PartialEq)]
pub struct Wiring(pub Vec<(Target, Source)>);

impl Wiring {
    /// Same as the overlay's default config.
    pub fn default_pocket() -> Self {
        let s = |ch| Source { ch, invert: false };
        Wiring(vec![
            (Target::RightX, s(1)),
            (Target::RightY, s(2)),
            (Target::LeftY, s(3)),
            (Target::LeftX, s(4)),
            (Target::SA, s(5)),
            (Target::SB, s(6)),
            (Target::SC, s(7)),
            (Target::S1, s(8)),
            (Target::SD, s(9)),
            (Target::SE, s(10)),
        ])
    }

    /// Random channels (analog controls on CH1-8, the rest anywhere) and random reversing.
    pub fn random(rng: &mut Rng) -> Self {
        let mut analog: Vec<usize> = (1..=8).collect();
        let mut any: Vec<usize> = Vec::new();
        rng.shuffle(&mut analog);
        let mut wiring = Vec::new();
        for t in pocket_overlay::learn::Target::ALL {
            if t.needs_analog() {
                let ch = analog.pop().unwrap();
                wiring.push((
                    t,
                    Source {
                        ch,
                        invert: rng.below(2) == 1,
                    },
                ));
            }
        }
        // 2-pos switches and SE: leftover analog channels or button channels 9-32
        any.extend(analog);
        any.extend(9..=32);
        rng.shuffle(&mut any);
        for t in [Target::SA, Target::SD, Target::SE] {
            wiring.push((
                t,
                Source {
                    ch: any.pop().unwrap(),
                    invert: rng.below(2) == 1,
                },
            ));
        }
        Wiring(wiring)
    }

    pub fn get(&self, t: Target) -> Option<Source> {
        self.0
            .iter()
            .find(|(target, _)| *target == t)
            .map(|(_, s)| *s)
    }

    pub fn channels(&self, radio: &Radio) -> [i16; edgetx::CHANNELS] {
        let mut ch = [0i16; edgetx::CHANNELS];
        for (target, src) in &self.0 {
            let v = radio.mixer_value(*target) * if src.invert { -1.0 } else { 1.0 };
            ch[src.ch - 1] = (v * 1024.0).round() as i16;
        }
        ch
    }
}

/// Small deterministic PRNG (xorshift) so failures reproduce.
pub struct Rng(pub u64);

impl Rng {
    pub fn next(&mut self) -> u64 {
        self.0 ^= self.0 << 13;
        self.0 ^= self.0 >> 7;
        self.0 ^= self.0 << 17;
        self.0
    }
    pub fn below(&mut self, n: u64) -> u64 {
        self.next() % n
    }
    /// Uniform in -1..=1 on a 1/1024 grid, so it survives the trip exactly.
    pub fn unit(&mut self) -> f32 {
        (self.below(2049) as f32 - 1024.0) / 1024.0
    }
    pub fn shuffle<T>(&mut self, v: &mut [T]) {
        for i in (1..v.len()).rev() {
            v.swap(i, self.below(i as u64 + 1) as usize);
        }
    }
    pub fn radio(&mut self) -> Radio {
        Radio {
            left_x: self.unit(),
            left_y: self.unit(),
            right_x: self.unit(),
            right_y: self.unit(),
            sa: self.below(2) as u8,
            sb: self.below(3) as u8,
            sc: self.below(3) as u8,
            sd: self.below(2) as u8,
            se: self.below(2) == 1,
            s1: self.unit(),
        }
    }
}


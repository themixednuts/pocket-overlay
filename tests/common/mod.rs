pub fn edgetx_src() -> Option<PathBuf> {
    let dir = std::env::var_os("EDGETX_SRC")
        .map(PathBuf::from)
        .unwrap_or_else(|| Path::new(env!("CARGO_MANIFEST_DIR")).join("ref/edgetx"));
    let src = dir.join("radio/src");
    if src.join("targets/common/arm/stm32/usb_driver.cpp").exists() {
        Some(src)
    } else {
        eprintln!(
            "SKIPPED EdgeTX checks: no source at {} (see tests/edgetx_conformance.rs)",
            dir.display()
        );
        None
    }
}

pub fn read(src: &Path, rel: &str) -> String {
    std::fs::read_to_string(src.join(rel))
        .unwrap_or_else(|e| panic!("reading {rel}: {e}"))
        .replace("\r\n", "\n")
}

/// Text between `start` and the next `end` after it.
pub fn between<'a>(text: &'a str, start: &str, end: &str) -> &'a str {
    let from = text
        .find(start)
        .unwrap_or_else(|| panic!("{start:?} not found"))
        + start.len();
    let len = text[from..]
        .find(end)
        .unwrap_or_else(|| panic!("{end:?} not found after {start:?}"));
    &text[from..from + len]
}

pub fn find_cxx() -> Option<String> {
    let candidates = std::env::var("CXX")
        .into_iter()
        .chain(["clang++".into(), "g++".into()]);
    for cxx in candidates {
        if Command::new(&cxx)
            .arg("--version")
            .output()
            .is_ok_and(|o| o.status.success())
        {
            return Some(cxx);
        }
    }
    eprintln!("SKIPPED EdgeTX encoder: no C++ compiler (set CXX, or install clang++/g++)");
    None
}

/// `HID_JOYSTICK_ReportDesc` bytes straight from the EdgeTX source.
pub fn source_descriptor(src: &Path) -> Vec<u8> {
    let file = read(src, "targets/common/arm/stm32/usbd_hid_joystick.c");
    let body = between(&file, "HID_JOYSTICK_ReportDesc[] __ALIGN_END =", "};");
    body.lines()
        .map(|l| l.split("//").next().unwrap())
        .flat_map(|l| l.split(','))
        .map(str::trim)
        .filter_map(|t| t.strip_prefix("0x").or_else(|| t.strip_prefix("0X")))
        .map(|h| u8::from_str_radix(h, 16).expect("hex byte"))
        .collect()
}

/// A harness around the verbatim classic branch of EdgeTX's `usbJoystickUpdate()`.
/// Reads 32 channel values per line on stdin, prints each report as hex.
pub fn harness_source(src: &Path) -> String {
    let driver = read(src, "targets/common/arm/stm32/usb_driver.cpp");
    let func = between(&driver, "void usbJoystickUpdate()\n{", "\n}\n");
    let classic = between(func, "#if !defined(USBJ_EX)", "#else");

    let conf = read(src, "targets/common/arm/stm32/usbd_conf.h");
    let packet = between(&conf, "#define HID_IN_PACKET", "\n")
        .trim()
        .to_owned();

    let helpers = read(src, "edgetx_helpers.h");
    let limit_at = helpers
        .find("inline T limit(")
        .expect("limit() in edgetx_helpers.h");
    let template_at = helpers[..limit_at]
        .rfind("template")
        .expect("limit template");
    let limit_end = limit_at + helpers[limit_at..].find('}').expect("limit body") + 1;
    let limit = &helpers[template_at..limit_end];

    format!(
        r#"// generated by tests/common/mod.rs from EdgeTX source
#include <cstdint>
#include <cstdio>
#include <algorithm>
using std::min;
using std::max;

#define HID_IN_PACKET {packet}
{limit}

int16_t channelOutputs[32];
static int hUsbDevice;
static void USBD_HID_SendReport(int*, uint8_t* buf, int len) {{
  for (int i = 0; i < len; i++) printf("%02x", buf[i]);
  printf("\n");
  fflush(stdout);
}}

void usbJoystickUpdate() {{
{classic}
}}

int main() {{
  for (;;) {{
    for (int i = 0; i < 32; i++) {{
      int v;
      if (scanf("%d", &v) != 1) return 0;
      channelOutputs[i] = (int16_t)v;
    }}
    usbJoystickUpdate();
  }}
}}
"#
    )
}

/// Builds the harness once per test binary, reusing an existing build when the
/// generated source hasn't changed.
pub fn harness_exe() -> Option<PathBuf> {
    static EXE: OnceLock<Option<PathBuf>> = OnceLock::new();
    EXE.get_or_init(|| {
        let src = edgetx_src()?;
        let cxx = find_cxx()?;
        let dir = Path::new(env!("CARGO_TARGET_TMPDIR")).join("edgetx-harness");
        std::fs::create_dir_all(&dir).unwrap();
        let cpp = dir.join("harness.cpp");
        let exe = dir.join(if cfg!(windows) {
            "harness.exe"
        } else {
            "harness"
        });
        let code = harness_source(&src);
        let fresh = std::fs::read_to_string(&cpp).is_ok_and(|old| old == code) && exe.exists();
        if !fresh {
            std::fs::write(&cpp, &code).unwrap();
            let out = Command::new(&cxx)
                .args(["-std=c++17", "-O1"])
                .arg(&cpp)
                .arg("-o")
                .arg(&exe)
                .output()
                .unwrap();
            assert!(
                out.status.success(),
                "harness build failed:\n{}\n{code}",
                String::from_utf8_lossy(&out.stderr)
            );
        }
        Some(exe)
    })
    .clone()
}

pub fn parse_hex(line: &str) -> Vec<u8> {
    (0..line.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&line[i..i + 2], 16).unwrap())
        .collect()
}

pub fn to_hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

/// Turns channel values into report bytes: via EdgeTX's own code when available.
pub enum Encoder {
    Edgetx {
        child: Child,
        stdin: ChildStdin,
        stdout: BufReader<ChildStdout>,
    },
    Rust,
}

impl Encoder {
    pub fn best() -> Self {
        match harness_exe() {
            Some(exe) => {
                let mut child = Command::new(exe)
                    .stdin(Stdio::piped())
                    .stdout(Stdio::piped())
                    .spawn()
                    .unwrap();
                let stdin = child.stdin.take().unwrap();
                let stdout = BufReader::new(child.stdout.take().unwrap());
                Encoder::Edgetx {
                    child,
                    stdin,
                    stdout,
                }
            }
            None => Encoder::Rust,
        }
    }

    pub fn name(&self) -> &'static str {
        match self {
            Encoder::Edgetx { .. } => "EdgeTX usbJoystickUpdate()",
            Encoder::Rust => "Rust mirror (EdgeTX harness unavailable)",
        }
    }

    pub fn encode(&mut self, ch: &[i16; edgetx::CHANNELS]) -> Vec<u8> {
        match self {
            Encoder::Edgetx { stdin, stdout, .. } => {
                let line: Vec<String> = ch.iter().map(i16::to_string).collect();
                writeln!(stdin, "{}", line.join(" ")).unwrap();
                stdin.flush().unwrap();
                let mut out = String::new();
                stdout.read_line(&mut out).unwrap();
                parse_hex(out.trim())
            }
            Encoder::Rust => edgetx::encode_classic(ch).to_vec(),
        }
    }
}

impl Drop for Encoder {
    fn drop(&mut self) {
        if let Encoder::Edgetx { child, .. } = self {
            let _ = child.kill();
        }
    }
}

